// Writes docs/astryx/: the whole Astryx catalogue (every component, hook,
// page template and docs topic) as Markdown, from the CLI pinned in
// ui/package.json, so an agent can read what exists without network or a
// shell. Run it after an Astryx upgrade: `npm run astryx-catalog` (in ui/).
//
// The CLI stays the live source (`npm run astryx -- search <words>`); this
// is a committed snapshot of it at one version.

import { execFileSync } from "node:child_process"
import { mkdirSync, rmSync, writeFileSync, readFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ui = join(dirname(fileURLToPath(import.meta.url)), "..")
const out = join(ui, "..", "docs", "astryx")
const bin = join(ui, "node_modules", "@astryxdesign", "cli", "clients", "cli", "bin", "astryx.mjs")
const version = JSON.parse(readFileSync(join(ui, "node_modules", "@astryxdesign", "core", "package.json"), "utf8")).version

function cli(...args) {
  return execFileSync(process.execPath, [bin, ...args], { cwd: ui, encoding: "utf8", maxBuffer: 64 << 20, env: { ...process.env, NO_COLOR: "1" } })
}
const json = (...args) => JSON.parse(cli(...args, "--json")).data
const safe = (name) => name.replace(/[^A-Za-z0-9._-]/g, "_")
const oneLine = (s) => (s || "").replace(/\s+/g, " ").trim()
const header = (what) => `<!-- Generated by ui/scripts/astryx-catalog.mjs from @astryxdesign/cli ${version}. Do not edit; rerun the script. -->\n\n${what}\n`

rmSync(out, { recursive: true, force: true })
for (const d of ["components", "hooks", "templates", "topics"]) mkdirSync(join(out, d), { recursive: true })

// Components: the CLI groups related ones (Tabs: TabList, Tab, TabMenu).
// Every member gets its own file with its full props; the index lists them
// by group with each one-line description.
const comps = json("component", "--list", "--detail", "compact").components
const index = []
for (const [group, members] of Object.entries(comps)) {
  for (const m of members) {
    try {
      writeFileSync(join(out, "components", `${safe(m.name)}.md`), header("") + cli("component", m.name, "--dense"))
    } catch (e) {
      console.warn(`skipped ${m.name}: ${String(e.message).split("\n")[0]}`)
    }
  }
  const lead = members.find((m) => m.name === group) || members[0]
  const subs = members.filter((m) => m !== lead).map((m) => m.name)
  index.push({ group, lead: lead.name, pkg: lead.package, desc: oneLine(lead.description), subs })
}
const componentCount = Object.values(comps).flat().length

// Hooks and page templates.
const hooks = json("hook", "--list", "--detail", "compact")
const hookList = Object.values(hooks.components || hooks.hooks || {}).flat().filter(Boolean)
for (const h of hookList) writeFileSync(join(out, "hooks", `${safe(h.name)}.md`), header("") + cli("hook", h.name, "--dense"))
const templates = json("template", "--list", "--detail", "compact")
const tplList = (Array.isArray(templates) ? templates : Object.values(templates)).filter((t) => t && t.id)
for (const t of tplList) writeFileSync(join(out, "templates", `${safe(t.id)}.md`), header("") + cli("template", t.id))

// Docs topics: every topic, walking each namespace's children (a topic's
// route is how `astryx docs <route>` opens it).
const topicsData = json("docs")
const topics = Array.isArray(topicsData) ? topicsData : topicsData.topics || []
const topicRows = []
const seen = new Set()
function writeTopic(route) {
  if (seen.has(route)) return
  seen.add(route)
  let node = null
  try {
    node = json("docs", route)
  } catch {
    return
  }
  writeFileSync(join(out, "topics", `${safe(route.replaceAll("/", "__"))}.md`), header("") + cli("docs", route, "--dense"))
  for (const slot of node.slots || []) for (const k of slot.children || []) if (k.route) writeTopic(k.route)
}
for (const t of topics) {
  const name = t.topic || t.name || t.id
  topicRows.push({ name, desc: oneLine(t.description || t.summary) })
  writeTopic(name)
}

const rows = (xs, f) => xs.map(f).join("\n")
writeFileSync(
  join(out, "README.md"),
  header(`# Astryx catalogue (${version})

suzuri's chrome (everything around the terminal panes) is built with
[Astryx](https://astryx.atmeta.com), Meta's MIT design system, theme Neutral.
Before building any UI, pick from what is listed here; don't hand-roll a
control Astryx already has.

- Live, searchable: \`npm run astryx -- search <words>\` in \`ui/\`
  (\`component <Name>\`, \`hook <name>\`, \`template <id>\`, \`docs <topic>\`).
  Never run a bare \`npx astryx\`: that name is an unrelated npm package.
- This folder is a snapshot of the same docs at ${version}, regenerated by
  \`npm run astryx-catalog\` in \`ui/\` after an upgrade.

## Components (${componentCount} in ${index.length} groups)

| Component | Import | Parts | What it is |
|---|---|---|---|
${rows(index, (c) => `| [${c.lead}](components/${safe(c.lead)}.md) | \`${c.pkg}/${c.lead}\` | ${c.subs.map((x) => `[${x}](components/${safe(x)}.md)`).join(", ")} | ${c.desc.replace(/\|/g, "\\|")} |`)}

## Hooks (${hookList.length})

${rows(hookList, (h) => `- [${h.name}](hooks/${safe(h.name)}.md): ${oneLine(h.description).replace(/\|/g, "\\|")}`)}

## Page templates (${tplList.length})

${rows(tplList, (t) => `- [${t.name}](templates/${safe(t.id)}.md) (\`${t.id}\`): ${oneLine(t.description)}`)}

## Docs topics

${rows(topicRows, (t) => `- [${t.name}](topics/${safe(t.name)}.md): ${t.desc}`)}
`),
)
console.log(`docs/astryx: ${componentCount} components, ${hookList.length} hooks, ${tplList.length} templates, ${seen.size} docs pages (Astryx ${version})`)
